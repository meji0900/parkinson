// Copies what the app needs from the Foundry project: the registry ABI (lib/chain/abi.ts, typed `as const` for viem)
// and every deployment the Deploy script broadcast (lib/chain/deployments.json, keyed by chain id). Run it after
// `npm run chain:build` and after every deploy; chain:deploy runs it for you.
//   node scripts/chain-sync.mjs
import fs from "node:fs";
import path from "node:path";
import { getAddress } from "viem";

const root = process.cwd();
const out = path.join(root, "contracts", "out", "ParkinsonRegistry.sol", "ParkinsonRegistry.json");
if (!fs.existsSync(out)) {
  console.error("no build output; run npm run chain:build first");
  process.exit(1);
}
const abi = JSON.parse(fs.readFileSync(out, "utf8")).abi;
fs.writeFileSync(
  path.join(root, "lib", "chain", "abi.ts"),
  `// Generated by scripts/chain-sync.mjs from contracts/src/ParkinsonRegistry.sol. Do not edit by hand.\nexport const registryAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`abi: ${abi.filter((x) => x.type === "function").length} functions, ${abi.filter((x) => x.type === "event").length} events`);

const file = path.join(root, "lib", "chain", "deployments.json");
const deployments = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : {};
const dir = path.join(root, "contracts", "broadcast", "Deploy.s.sol");
for (const chainId of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
  const run = path.join(dir, chainId, "run-latest.json");
  if (!fs.existsSync(run)) continue;
  const { transactions = [], receipts = [], timestamp } = JSON.parse(fs.readFileSync(run, "utf8"));
  const made = {}, txs = {};
  let deployer = null;
  for (const tx of transactions) {
    if (tx.transactionType !== "CREATE" || !tx.contractName || !tx.contractAddress) continue;
    made[tx.contractName] = getAddress(tx.contractAddress);
    txs[tx.contractName] = tx.hash;
    deployer ??= getAddress(tx.transaction.from);
  }
  if (!made.ParkinsonRegistry) continue;
  const at = receipts.find((r) => r.contractAddress?.toLowerCase() === made.ParkinsonRegistry.toLowerCase());
  // the page shows these as the proof of deployment; a later deploy without a test token must not keep the old one
  deployments[chainId] = {
    ParkinsonRegistry: made.ParkinsonRegistry,
    ...(made.ParkinsonTestToken ? { ParkinsonTestToken: made.ParkinsonTestToken } : {}),
    block: at ? Number(at.blockNumber) : null,
    at: timestamp ? new Date(timestamp).toISOString().replace(/\.\d{3}Z$/, "Z") : null,
    deployer,
    txs,
  };
  console.log(`chain ${chainId}: ${Object.entries(deployments[chainId]).filter(([, v]) => typeof v !== "object").map(([k, v]) => `${k} ${v}`).join(", ")}`);
}
fs.writeFileSync(file, JSON.stringify(deployments, null, 2) + "\n");
console.log(`wrote ${path.relative(root, file)}`);
